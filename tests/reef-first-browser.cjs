// Functional checks only; no screenshots, previews or archives.
const { chromium } = require('./browser-support.cjs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.clock.install();
    await page.addInitScript(() => localStorage.setItem('beach-pairs-unlock-all', 'on'));
    await page.goto(pathToFileURL(path.join(__dirname, '..', 'index.html')).href);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    const state = () => page.evaluate(() => beachDiagnostics.snapshot());
    const action = name => page.getByRole('button', { name, exact: true }).click();
    const tile = index => page.locator('.tile').nth(index);
    const initialGrass = [4,9,11,16,19,24,26,31];
    await page.locator('#select-level-button').click();
    await page.locator('#chapter-next').click(); await page.locator('#chapter-next').click();
    assert.equal(await page.locator('#level-21').isEnabled(), true);
    assert.equal(await page.locator('#level-35').isDisabled(), false);
    await page.locator('#level-21').click();
    assert.equal(await page.locator('#play-chapter').innerText(), '礁间寻宝');
    assert.equal(await page.locator('#play-number').innerText(), '01');
    assert.equal(await page.locator('#modal-heading').innerText(), '当太阳升起，你发现自己到了礁石岸边！');
    assert.match(await page.locator('#modal-description').innerText(), /被海草覆盖的格子可以直接翻开，如果配对成功则会正常消除/);
    assert.match(await page.locator('#modal-description').innerText(), /如果配对失败，一段时间内该格将被海草缠绕，不可再翻开，且四面相邻的格子都会被海草覆盖/);
    assert.equal(await page.locator('#modal-art svg').count(), 1);
    assert.equal(await page.locator('.tile').count(), 36);
    assert.deepEqual((await state()).seagrass.flatMap((card, i) => card.grass ? [i] : []), initialGrass);
    const deck = await page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind)));
    for (const viewport of [{width:320,height:568}, {width:390,height:844}]) {
      await page.setViewportSize(viewport);
      assert.equal(await page.locator('#modal-card').evaluate(element => {
        const box = element.getBoundingClientRect();
        return box.top >= 0 && box.bottom <= innerHeight && element.scrollWidth <= element.clientWidth;
      }), true, JSON.stringify(viewport));
    }
    await page.clock.fastForward(30000); assert.equal((await state()).remaining, 60000);
    await action('我知道了');
    await tile(4).click(); await tile(3).click();
    assert.equal((await state()).seagrass[3].grass, false);
    assert.equal((await state()).seagrass[5].grass, true);
    assert.equal((await state()).seagrass[10].grass, true);
    await page.clock.runFor(520);
    assert.equal(await tile(4).isDisabled(), true);
    assert.match(await tile(4).getAttribute('aria-label'), /紫色交叉海草/);
    await page.locator('#pause-button').click(); await action('重新开始');
    assert.deepEqual((await state()).seagrass.flatMap((card, i) => card.grass ? [i] : []), initialGrass);
    assert.deepEqual(await page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind))), deck);
    assert.equal((await state()).remaining, 60000);
    await action('我知道了');
    for (const kind of [0,1,2,4,5]) for (let i = 0; i < deck.length; i++) if (deck[i] === kind) await tile(i).click();
    await page.clock.runFor(800);
    assert.equal((await state()).state, 'won'); assert.equal((await state()).pairs, 18);
    assert.equal(await page.locator('#modal-art .bucket-find').count(), 18);
    await action('下一关');
    assert.equal((await state()).levelId, 22);
    assert.equal((await state()).modalOpen, false); assert.equal((await state()).timerRunning, true);
    assert.equal((await state()).duration, 60000); assert.deepEqual((await state()).conditions, []);
    assert.equal(await page.locator('#play-chapter').innerText(), '礁间寻宝');
    assert.equal(await page.locator('#play-number').innerText(), '02');
    assert.equal(await page.locator('#play-reef-scene').isVisible(), true);
    assert.equal(await page.locator('.tile').count(), 36);
    const secondGrass = [2,5,7,10,12,15,20,23,25,28,30,33];
    assert.deepEqual((await state()).seagrass.flatMap((card, i) => card.grass ? [i] : []), secondGrass);
    const secondDeck = await page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind)));
    assert.notDeepEqual(secondDeck, deck);
    await tile(2).click(); await tile(3).click(); await page.clock.runFor(520);
    assert.match(await tile(2).getAttribute('aria-label'), /紫色交叉海草/);
    assert.equal((await state()).seagrass[3].grass, false);
    assert.equal((await state()).seagrass[1].grass, true); assert.equal((await state()).seagrass[8].grass, true);
    await page.locator('#pause-button').click(); const pausedSecond = await state();
    await page.clock.fastForward(30000); assert.equal((await state()).activeTime, pausedSecond.activeTime);
    await action('重新开始'); assert.equal((await state()).modalOpen, false);
    assert.deepEqual((await state()).seagrass.flatMap((card, i) => card.grass ? [i] : []), secondGrass);
    assert.deepEqual(await page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind))), secondDeck);
    for (const kind of [0,1,2,4,5]) for (let i = 0; i < secondDeck.length; i++) if (secondDeck[i] === kind) await tile(i).click();
    await page.clock.runFor(800);
    assert.equal((await state()).state, 'won'); assert.equal((await state()).pairs, 18);
    assert.equal(await page.locator('#modal-art .bucket-find').count(), 18);
    await action('下一关');
    assert.equal((await state()).levelId, 23);
    assert.equal(await page.locator('#modal-conditions').innerText(), '在5秒内完成3次配对');
    await action('我知道了'); await page.locator('#pause-button').click();
    await action('返回选关');
    assert.equal(await page.locator('#level-22').isEnabled(), true);
    assert.equal(await page.locator('#level-35').isDisabled(), false);
    await page.locator('#level-22').click();
    assert.deepEqual((await state()).seagrass.flatMap((card, i) => card.grass ? [i] : []), secondGrass);
    assert.deepEqual(await page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind))), secondDeck);
    assert.deepEqual(errors, []);
    console.log('PASS: first-to-second reef progression, eight/twelve swapped grass patterns, second level direct timed start, independent fixed decks, propagation, purple lock, pause/retry/reentry, both victories and unlock selection. No images captured.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
