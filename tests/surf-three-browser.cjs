// Uses existing Chrome only; functional checks produce no screenshots or archives.
const { chromium } = require('./browser-support.cjs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
    await page.clock.install({ time: new Date('2026-11-02T00:00:00Z') });
    await page.clock.pauseAt(new Date('2026-11-02T00:00:01Z'));
    await page.addInitScript(() => { localStorage.setItem('beach-pairs-unlock-all', 'on'); Math.random = () => 0; });
    await page.goto(pathToFileURL(path.join(__dirname, '..', 'index.html')).href);
    const state = () => page.evaluate(() => beachDiagnostics.snapshot());
    const action = name => page.getByRole('button', { name, exact: true }).click();
    const tile = index => page.locator('.tile').nth(index);
    const pair = async (a,b) => { await tile(a).click(); await tile(b).click(); };
    await page.locator('#select-level-button').click();
    for (let i = 0; i < 3; i++) await page.locator('#chapter-next').click();
    assert.equal(await page.locator('#chapter-4 .chapter-level:enabled').count(), 10);
    assert.equal(await page.locator('#level-49').isDisabled(), true);
    // Enter through the second level's real victory/next-level flow.
    await page.locator('#level-32').click(); await action('我知道了');
    const second = await page.locator('.tile .seaside-item').evaluateAll(items => items.map(item => Number(item.dataset.kind)));
    for (const kind of [0,1,2,3,4,5]) for (let i = 0; i < second.length; i++) if (second[i] === kind) await tile(i).click();
    await page.clock.runFor(1000); await action('下一关'); assert.equal((await state()).levelId, 33);
    const label = '配对失败的次数不能超过20次';
    const progress = n => `配对失败的次数不能超过 ${n} / 20次`;
    const condition = page.locator('#play-conditions .condition-item');
    assert.equal(await page.locator('#play-number').innerText(), '03');
    assert.equal(await page.locator('#modal-art .notice-board-art').count(), 1);
    assert.equal(await page.locator('#modal-conditions').innerText(), label);
    assert.equal(await page.locator('#play-conditions').innerText(), progress(0));
    assert.deepEqual((await state()).conditions.map(item => item.type), ['maxMismatches']);
    const deck = await page.locator('.tile .seaside-item').evaluateAll(items => items.map(item => Number(item.dataset.kind)));
    assert.deepEqual([0,1,2,3,4,5].map(kind => deck.filter(value => value === kind).length), [6,6,6,6,6,6]);
    assert.notDeepEqual(deck, second);
    await page.clock.fastForward(90000); assert.equal((await state()).remaining, 60000); assert.equal((await state()).surf.time, 0);
    await action('我知道了');
    await tile(0).click(); await tile(0).dispatchEvent('click'); assert.equal((await state()).mismatches, 0);
    await tile(1).click(); await tile(2).dispatchEvent('click'); assert.equal((await state()).mismatches, 1);
    await page.clock.runFor(520);
    for (let i = 1; i < 20; i++) { await pair(0,1); await page.clock.runFor(520); }
    assert.equal((await state()).mismatches, 20); assert.equal((await state()).state, 'playing');
    assert.equal(await page.locator('#play-conditions').innerText(), progress(20));
    assert.equal(await condition.getAttribute('data-completed'), 'false');
    await page.locator('#pause-button').click(); assert.equal(await page.locator('#modal-conditions').innerText(), progress(20));
    const paused = await state(); await page.clock.fastForward(30000);
    assert.equal((await state()).surf.time, paused.surf.time); assert.equal((await state()).mismatches, 20);
    await action('继续赶海');
    await page.clock.runFor(12100 - (await state()).surf.time);
    assert.equal((await state()).surf.phase, 'warning'); assert.equal((await state()).surf.target.axis, 'row');
    await page.clock.runFor(3000); const beforeWave = await state();
    assert.equal(beforeWave.surf.phase, 'arriving'); assert.equal(beforeWave.surf.count, 1);
    for (let i = 0; i < 6; i++) await tile(i).dispatchEvent('click');
    assert.equal((await state()).mismatches, 20);
    const a = deck.findIndex((kind,index) => index >= 6 && deck.some((other,j) => j >= 6 && j !== index && other === kind));
    const b = deck.findIndex((kind,index) => index >= 6 && index !== a && kind === deck[a]);
    await pair(a,b); assert.ok((await state()).flights > 0);
    const failA = deck.findIndex((_,index) => index >= 6 && index !== a && index !== b);
    const failB = deck.findIndex((kind,index) => index >= 6 && index !== a && index !== b && kind !== deck[failA]);
    await pair(failA,failB);
    assert.equal((await state()).mismatches, 21); assert.equal((await state()).failureReason, 'conditions');
    assert.equal(await page.locator('#modal-heading').innerText(), '未完成全部的条件');
    assert.equal(await page.locator('#modal-art .condition-failure-art').count(), 1);
    assert.ok((await state()).flights > 0, 'The failure dialog must not wait for collection animation.');
    assert.ok((await state()).remaining > 0); assert.ok((await state()).progress < 1);
    assert.equal(await page.evaluate(() => localStorage.getItem('beach-pairs-completed-levels')), null);
    await action('重新挑战'); assert.equal((await state()).mismatches, 0); assert.equal((await state()).surf.time, 0);
    assert.equal((await state()).surf.count, 0); assert.equal((await state()).remaining, 60000);
    assert.equal(await page.locator('#modal-conditions').innerText(), label);
    assert.deepEqual(await page.locator('.tile .seaside-item').evaluateAll(items => items.map(item => Number(item.dataset.kind))), deck);
    await action('我知道了');
    for (let i = 0; i < 20; i++) { await pair(0,1); await page.clock.runFor(520); }
    for (const kind of [0,1,2,3,4,5]) for (let i = 0; i < deck.length; i++) if (deck[i] === kind) await tile(i).click();
    assert.equal((await state()).state, 'won'); assert.equal((await state()).mismatches, 20);
    assert.equal((await state()).pairs, 18); assert.equal(await condition.getAttribute('data-completed'), 'true');
    await page.clock.runFor(1000); assert.equal(await page.locator('#modal-art .bucket-find').count(), 18);
    assert.equal(await page.evaluate(() => localStorage.getItem('beach-pairs-completed-levels')), null);
    await action('下一关'); assert.equal((await state()).levelId, 34);
    assert.deepEqual((await state()).conditions, []);
    await action('我知道了'); await page.locator('#pause-button').click(); await action('返回选关'); assert.equal(await page.locator('#level-33').isEnabled(), true);
    assert.equal(await page.locator('#level-49').isDisabled(), true);
    assert.deepEqual(errors, []); assert.deepEqual(requests, []);
    console.log('PASS: second-to-third entry, six-kind fixed board, three condition placements, intro/pause/retry, 15s wave warning/arrival, invalid/washed input exclusion, immediate 21st-mistake red cross during collection, 20-mistake victory and progress isolation. No images captured.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
