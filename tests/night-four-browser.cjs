// Functional browser verification only; no previews or packages.
const { chromium } = require('C:/Users/29781/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install();
    await page.addInitScript(() => localStorage.setItem('beach-pairs-unlock-all', 'on'));
    await page.goto(pathToFileURL(path.join(__dirname, '..', 'index.html')).href);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    const state = () => page.evaluate(() => beachDiagnostics.snapshot());
    const action = name => page.getByRole('button', { name, exact: true }).click();
    const tile = index => page.locator('.tile').nth(index);
    const deck = () => page.locator('.tile .seaside-item').evaluateAll(icons => icons.map(icon => Number(icon.dataset.kind)));
    await page.locator('#select-level-button').click();
    await page.locator('#chapter-next').click();
    assert.equal(await page.locator('#level-14').isEnabled(), true);
    assert.equal(await page.locator('#level-31').isDisabled(), true);
    await page.locator('#level-14').click();
    assert.equal((await state()).levelId, 14);
    assert.equal((await state()).duration, 60000);
    assert.equal(await page.locator('#play-number').innerText(), '04');
    assert.equal(await page.locator('#modal-art .notice-board-art').count(), 1);
    assert.equal(await page.locator('#modal-conditions').innerText(), '最后一对配对必须是螃蟹');
    assert.equal(await page.locator('#modal-conditions .seaside-item[data-kind="1"]').count(), 1);
    assert.equal(await page.locator('.fog-mask-cell').count(), 12);
    const fog = (await state()).fog.map(cell => Boolean(cell));
    assert.deepEqual(Array.from({ length: 6 }, (_, row) => fog.slice(row * 6, row * 6 + 6).map(covered => covered ? '#' : '.').join('')), ['.#..#.', '.#.#..', '.##...', '.##...', '.#.#..', '.#..#.']);
    assert.equal((await state()).fog[12], null);
    const original = await deck();
    assert.deepEqual([0, 1, 2, 4, 5].map(kind => original.filter(value => value === kind).length), [10, 2, 8, 8, 8]);
    await page.reload();
    await page.locator('#select-level-button').click();
    await page.locator('#chapter-next').click();
    await page.locator('#level-14').click();
    assert.notDeepEqual(await deck(), original, 'A fresh entry after reload reshuffles this level.');
    await page.clock.fastForward(90000);
    assert.equal((await state()).remaining, 60000);
    await action('我知道了');
    assert.equal(await page.locator('#play-conditions .seaside-item[data-kind="1"]').count(), 1);
    await tile(1).click();
    assert.equal((await state()).statuses[1], 'hidden');
    await page.locator('#pause-button').click();
    assert.equal(await page.locator('#modal-conditions .seaside-item[data-kind="1"]').count(), 1);
    assert.equal(await page.locator('#modal-conditions .condition-item').getAttribute('data-completed'), 'false');
    await page.clock.fastForward(10000);
    assert.equal((await state()).fog[1].covered, false);
    await action('继续赶海');
    await page.clock.runFor(5100);
    assert.equal((await state()).fog[1].covered, true);
    async function finish(order) {
      const values = await deck();
      for (const kind of order) for (let index = 0; index < values.length; index++) if (values[index] === kind) {
        if ((await state()).fog[index]?.covered) await tile(index).click();
        await tile(index).click();
      }
      await page.clock.runFor(800);
    }
    await finish([1, 2, 4, 5, 0]);
    assert.equal((await state()).failureReason, 'conditions');
    assert.equal(await page.locator('#modal-heading').innerText(), '未完成全部的条件');
    assert.equal(await page.locator('#modal-art .condition-failure-art').count(), 1);
    await action('重新挑战');
    assert.notDeepEqual(await deck(), original);
    assert.equal(await page.locator('.tile[data-fog="covered"]').count(), 12);
    await action('我知道了');
    await finish([0, 2, 4, 5, 1]);
    assert.equal((await state()).state, 'won');
    assert.equal((await state()).lastMatchedKind, 1);
    assert.equal(await page.locator('#modal-art .bucket-find').count(), 18);
    await action('下一关');
    assert.equal((await state()).levelId, 15);
    assert.equal(await page.locator('#modal-heading').innerText(), '挑战！');
    await action('我知道了');
    await page.locator('#pause-button').click();
    await action('返回选关');
    await page.locator('#level-14').click();
    assert.notDeepEqual(await deck(), original);
    await action('我知道了');
    await page.clock.fastForward(61000);
    await page.clock.runFor(800);
    assert.equal((await state()).failureReason, 'timeout');
    assert.deepEqual(errors, []);
    console.log('PASS: night level four with twelve reference-marked fog cells, one crab pair, randomized entries/retries, crab icon in three condition displays, frozen intro/pause, fog restoration, early-crab failure, crab-last victory and timeout. No images captured.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
